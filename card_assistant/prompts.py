def build_user_message(product: ProductInput, contradictions: list[Contradiction]) -> str:
    data = json.dumps(product.model_dump(), ensure_ascii=False, indent=2)
    # Текст паспорта не должен закрыть блок данных раньше времени
    data = data.replace("<", "\\u003c")
    message = f"<product_data>\n{data}\n</product_data>"
    if contradictions:
        keys = ", ".join(f"«{item.key}»" for item in contradictions)
        message += (
            f"\n\nЗначения полей {keys} во входе противоречат друг другу. "
            "Не называй эти значения в тексте."
        )
    return message + "\n\nВерни объект JSON по описанной схеме."


def build_retry_message(issues: list[Issue]) -> str:
    lines = "\n".join(f"- {issue.field}: {issue.message}" for issue in issues)
    return (
        "В твоём ответе есть ошибки:\n"
        f"{lines}\n\n"
        "Исправь только их, остальное сохрани. Нельзя заменять ошибочное значение другим "
        "выдуманным: убери его из текста. Верни весь объект JSON целиком."
    )
